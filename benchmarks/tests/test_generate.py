import re
from pathlib import Path

import generate
import pytest

ROOT = Path(__file__).resolve().parents[2]
SQLX = ROOT / "dataform" / "definitions" / "intermediate" / "licitaciones.sqlx"


def silver_columns() -> list[str]:
    block = re.search(r"const columnas = \[(.*?)\];", SQLX.read_text(encoding="utf-8"), re.DOTALL)
    return re.findall(r'"([^"]+)"', block.group(1))


def test_another_seed_gives_another_text():
    assert generate.render(generate.SEED, generate.ROWS) != generate.render(generate.SEED + 1, generate.ROWS)


def test_header_has_the_three_fixed_lines():
    lines = generate.render(generate.SEED, generate.ROWS).splitlines()
    assert lines[:3] == [
        "-- generated by benchmarks/generate.py; do not edit",
        f"-- seed: {generate.SEED}",
        f"-- target rows: {generate.ROWS}",
    ]


def test_generate_array_bounds_multiply_to_rows():
    sql = generate.render(generate.SEED, generate.ROWS)
    bounds = [int(end) + 1 for end in re.findall(r"GENERATE_ARRAY\(0, (\d+)\)", sql)]
    assert len(bounds) == 2
    assert bounds[0] * bounds[1] == generate.ROWS


def test_no_clock_or_random_functions():
    sql = generate.render(generate.SEED, generate.ROWS)
    for forbidden in ("CURRENT_", "RAND(", "GENERATE_UUID"):
        assert forbidden not in sql
    assert ";" not in sql.split("\n", 3)[3]
    assert sql.endswith("\n")


def test_outer_select_projects_the_silver_columns_in_order():
    sql = generate.render(generate.SEED, generate.ROWS)
    outer = sql.split("\nSELECT\n", 1)[1].split("\nFROM (\n", 1)[0]
    projected = [re.search(r"(?:AS )?(\w+),?$", line.strip()).group(1) for line in outer.splitlines()]
    assert projected == silver_columns()
    assert len(projected) == 17


@pytest.mark.parametrize("rows", [29_999_000, 50_001_000, 40_000_500])
def test_rows_out_of_range_or_not_multiple_raise(rows):
    with pytest.raises(ValueError):
        generate.render(generate.SEED, rows)


def test_cli_writes_the_versioned_generate_sql(tmp_path):
    out = tmp_path / "gen.sql"
    assert generate.main(["--out", str(out)]) == 0
    assert out.read_bytes() == (ROOT / "benchmarks" / "generate.sql").read_bytes()
