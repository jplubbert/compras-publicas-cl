"""Deterministic SQL that generates the synthetic tenders of the benchmark (REQ-013, DEC-007, S-12).

render(seed, rows) returns one SELECT (no DDL, no ";") with the 17 columns of silver.licitaciones, built from
GENERATE_ARRAY and FARM_FINGERPRINT with a fixed seed, so the same seed always gives the same rows. variants.sql wraps
it three times. benchmarks/generate.sql is this module's output with SEED and ROWS, and is versioned.
"""

import argparse
from pathlib import Path

SEED = 20261021
ROWS = 40_000_000
INNER = 1000
MIN_ROWS = 30_000_000
MAX_ROWS = 50_000_000

# ESTADOS_LICITACION of dataform/includes/silver.js.
ESTADOS = {5: "Publicada", 6: "Cerrada", 7: "Desierta", 8: "Adjudicada", 18: "Revocada", 19: "Suspendida"}
TIPOS = ("L1", "LE", "LP", "LQ", "LR")
HASHES = ("estado", "tipo", "organismo", "moneda", "monto", "fecha", "creacion", "cierre", "adjudicacion", "ts")

DEFAULT_OUT = Path(__file__).resolve().parent / "generate.sql"


def _pick(values: list[str], hash_column: str) -> str:
    return f"[{', '.join(values)}][OFFSET(ABS(MOD({hash_column}, {len(values)})))]"


def render(seed: int, rows: int) -> str:
    if not MIN_ROWS <= rows <= MAX_ROWS:
        raise ValueError(f"rows must be between {MIN_ROWS} and {MAX_ROWS} (S-12), got {rows}")
    if rows % INNER:
        raise ValueError(f"rows must be a multiple of {INNER}, got {rows}")
    hashes = ",\n".join(
        f"      FARM_FINGERPRINT(CONCAT('{seed}:', '{name}:', CAST(id AS STRING))) AS h_{name}" for name in HASHES
    )
    estado_case = " ".join(f"WHEN {code} THEN '{name}'" for code, name in ESTADOS.items())
    codigos = _pick([str(code) for code in ESTADOS], "h_estado")
    tipos = _pick([f"'{tipo}'" for tipo in TIPOS], "h_tipo")
    lines = [
        "-- generated by benchmarks/generate.py; do not edit",
        f"-- seed: {seed}",
        f"-- target rows: {rows}",
        "SELECT",
        "  FORMAT('BENCH-%09d', id) AS codigo_licitacion,",
        "  CONCAT('Licitación sintética ', CAST(id AS STRING)) AS nombre,",
        "  codigo_estado,",
        f"  CASE codigo_estado {estado_case} END AS estado,",
        f"  {tipos} AS tipo,",
        "  codigo_organismo,",
        "  CONCAT('Organismo ', codigo_organismo) AS nombre_organismo,",
        (
            "  CASE WHEN ABS(MOD(h_moneda, 100)) < 90 THEN 'CLP' WHEN ABS(MOD(h_moneda, 100)) < 95 THEN 'CLF'"
            " ELSE 'USD' END AS moneda,"
        ),
        "  CAST(ABS(MOD(h_monto, 500000000)) AS NUMERIC) AS monto_estimado,",
        "  DATE_SUB(fecha_publicacion, INTERVAL ABS(MOD(h_creacion, 10)) DAY) AS fecha_creacion,",
        "  fecha_publicacion,",
        "  DATE_ADD(fecha_publicacion, INTERVAL 5 + ABS(MOD(h_cierre, 30)) DAY) AS fecha_cierre,",
        (
            "  IF(codigo_estado = 8,"
            " DATE_ADD(fecha_publicacion, INTERVAL 5 + ABS(MOD(h_cierre, 30)) + 1 + ABS(MOD(h_adjudicacion, 30)) DAY),"
            " NULL) AS fecha_adjudicacion,"
        ),
        f"  'bench-{seed}' AS run_id,",
        "  fecha_publicacion AS _ingest_date,",
        "  TIMESTAMP_ADD(TIMESTAMP(fecha_publicacion), INTERVAL ABS(MOD(h_ts, 86400)) SECOND) AS ingested_at,",
        "  TIMESTAMP_ADD(TIMESTAMP(fecha_publicacion), INTERVAL ABS(MOD(h_ts, 86400)) SECOND) AS fecha_cambio",
        "FROM (",
        "  SELECT",
        "    *,",
        f"    {codigos} AS codigo_estado,",
        "    CAST(1000 + ABS(MOD(h_organismo, 2000)) AS STRING) AS codigo_organismo,",
        "    DATE_ADD(DATE '2021-01-01', INTERVAL ABS(MOD(h_fecha, 1826)) DAY) AS fecha_publicacion",
        "  FROM (",
        "    SELECT",
        "      id,",
        hashes,
        "    FROM (",
        f"      SELECT a * {INNER} + b AS id",
        (
            f"      FROM UNNEST(GENERATE_ARRAY(0, {rows // INNER - 1})) AS a"
            f" CROSS JOIN UNNEST(GENERATE_ARRAY(0, {INNER - 1})) AS b"
        ),
        "    )",
        "  )",
        ")",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the deterministic benchmark generator SQL.")
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--rows", type=int, default=ROWS)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(args.seed, args.rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
